// Helper functions
export const getProgramsByCategory = (category: Category): Program[] => {
  return programs.filter(p => p.category === category);
};

export const getProgramsByType = (type: ProgramType): Program[] => {
  return programs.filter(p => p.type === type);
};

export const getProgramBySlug = (slug: string): Program | undefined => {
  return programs.find(p => p.slug === slug);
};

export const getCategories = (): Category[] => [
  'Software Engineering',
  'Data & Analytics',
  'AI & Machine Learning',
  'Cloud & DevOps',
  'Cybersecurity',
  'Low-Code & Business Apps',
];

export const getCareerTrackCategories = (): Category[] => {
  const cats = new Set<Category>();
  programs.filter(p => p.type === 'career-track').forEach(p => cats.add(p.category));
  return getCategories().filter(c => cats.has(c));
};

export const getShortCourseCategories = (): Category[] => {
  const cats = new Set<Category>();
  programs.filter(p => p.type === 'short-course').forEach(p => cats.add(p.category));
  return getCategories().filter(c => cats.has(c));
};

export const getCategoryProgramCounts = (): Record<Category, number> => {
  const counts = {} as Record<Category, number>;
  getCategories().forEach(c => { counts[c] = 0; });
  programs.forEach(p => { counts[p.category]++; });
  return counts;
};
